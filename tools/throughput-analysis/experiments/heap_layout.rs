//! Analysis only: fixed SSE2 instruction loops, varied placement, shared data.
//! Assembly is generated and byte-checked by prepare_heap_layout.py.
use std::{hint::black_box, time::Instant};
core::arch::global_asm!(include_str!("scan.S"), options(att_syntax));
include!("scan_declarations.rs");

fn random(state: &mut u64) -> u64 {
    *state ^= *state << 13;
    *state ^= *state >> 7;
    *state ^= *state << 17;
    *state
}

#[inline(never)]
fn measure(kernel: Kernel, cases: &[Vec<u64>], epochs: u64, expected: u64) -> f64 {
    // All kernels use the same call boundary, driver and data addresses.
    for case in cases {
        // SAFETY: every case has size >= 4, divisible by four; the kernel reads
        // only that initialized slice, clobbers caller-saved registers, and sums
        // with wrapping u64 arithmetic. Generated bytes are checked before use.
        assert_eq!(
            unsafe { kernel(case.as_ptr(), case.len()) },
            case.iter().fold(0u64, |a, b| a.wrapping_add(*b))
        );
    }
    let mut sum = 0u64;
    let start = Instant::now();
    for _ in 0..epochs {
        for case in cases {
            // SAFETY: same validated live slices as the warmup above.
            sum = sum.wrapping_add(black_box(unsafe {
                kernel(black_box(case.as_ptr()), black_box(case.len()))
            }));
        }
    }
    let elapsed = start.elapsed().as_secs_f64();
    assert_eq!(sum, expected.wrapping_mul(epochs));
    black_box(sum);
    elapsed
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let size: usize = args[1].parse().unwrap();
    let seed: u64 = args[2].parse().unwrap();
    let epochs: u64 = args[3].parse().unwrap();
    assert!(size >= 4 && size.is_multiple_of(4) && epochs > 0);
    let mut state = seed;
    let mut cases: Vec<Vec<u64>> = (0..64)
        .map(|_| (0..size).map(|_| random(&mut state)).collect())
        .collect();
    for i in (1..cases.len()).rev() {
        let j = random(&mut state) as usize % (i + 1);
        cases.swap(i, j);
    }
    let expected = cases.iter().flatten().fold(0u64, |a, v| a.wrapping_add(*v));
    let mut order: Vec<usize> = (0..KERNELS.len()).collect();
    for i in (1..order.len()).rev() {
        let j = random(&mut state) as usize % (i + 1);
        order.swap(i, j);
    }
    for i in order {
        let (name, kernel) = KERNELS[i];
        let seconds = measure(black_box(kernel), &cases, epochs, expected);
        println!(
            "{{\"kernel\":\"{name}\",\"size\":{size},\"seed\":{seed},\"epochs\":{epochs},\"operations\":{},\"elements\":{},\"checksum\":{},\"seconds\":{seconds}}}",
            epochs * 64,
            epochs * 64 * size as u64,
            expected.wrapping_mul(epochs)
        );
    }
}
